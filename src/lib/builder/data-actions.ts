import type { Dashboard, DataSource, Dataset, RawTable, SourceConfig, TransformStep } from "@/lib/model/types";
import { uid } from "@/lib/utils";

/** Pure draft updates for the Data tab. Each returns a new Dashboard. */

export function addSource(
  d: Dashboard,
  input: { name: string; config: SourceConfig; table: RawTable | null; warnings?: string[]; datasetName?: string },
  ids: { sourceId: string; datasetId: string },
): { next: Dashboard; sourceId: string; datasetId: string } {
  const { sourceId, datasetId } = ids;
  const kind = input.config.kind;
  const source: DataSource = {
    id: sourceId,
    name: input.name,
    kind,
    status: "ready",
    config: input.config,
    rowCount: input.table?.rows.length ?? 0,
    columnCount: input.table?.columns.length ?? 0,
    lastRefreshedAt: new Date().toISOString(),
    warnings: input.warnings?.length ? input.warnings : undefined,
  };
  const dataset: Dataset = { id: datasetId, name: input.datasetName ?? datasetNameFrom(input.name, d.datasets), sourceId, steps: [] };
  return {
    sourceId,
    datasetId,
    next: {
      ...d,
      sources: [...d.sources, source],
      sourceData: input.table && kind !== "sample" ? { ...d.sourceData, [sourceId]: input.table } : d.sourceData,
      datasets: [...d.datasets, dataset],
    },
  };
}

export function datasetNameFrom(fileName: string, existing: Dataset[]): string {
  const base =
    fileName
      .replace(/\.(csv|tsv|txt|xlsx)$/i, "")
      .replace(/[_-]+/g, " ")
      .replace(/\s+/g, " ")
      .trim()
      .replace(/^\w/, (c) => c.toUpperCase()) || "Dataset";
  let name = base;
  let i = 2;
  while (existing.some((x) => x.name === name)) name = `${base} ${i++}`;
  return name;
}

export function updateSource(d: Dashboard, id: string, patch: Partial<DataSource>): Dashboard {
  return { ...d, sources: d.sources.map((s) => (s.id === id ? { ...s, ...patch } : s)) };
}

export function replaceSourceTable(d: Dashboard, id: string, table: RawTable, patch: Partial<DataSource> = {}): Dashboard {
  return {
    ...updateSource(d, id, {
      status: "ready",
      error: undefined,
      rowCount: table.rows.length,
      columnCount: table.columns.length,
      lastRefreshedAt: new Date().toISOString(),
      ...patch,
    }),
    sourceData: { ...d.sourceData, [id]: table },
  };
}

export function removeSource(d: Dashboard, id: string): Dashboard {
  const { [id]: _removed, ...rest } = d.sourceData;
  return {
    ...d,
    sources: d.sources.filter((s) => s.id !== id),
    sourceData: rest,
    datasets: d.datasets.filter((ds) => ds.sourceId !== id),
  };
}

/** Ids are generated by the caller so reducer recipes stay pure. */
export function newIds() {
  return { sourceId: uid("src"), datasetId: uid("ds") };
}

export function addDataset(d: Dashboard, sourceId: string, datasetId: string, from?: Dataset): { next: Dashboard; datasetId: string } {
  const source = d.sources.find((s) => s.id === sourceId);
  const name = from ? datasetNameFrom(`${from.name} copy`, d.datasets) : datasetNameFrom(source?.name ?? "Dataset", d.datasets);
  const steps: TransformStep[] = from ? from.steps.map((s, i) => ({ ...s, id: `${datasetId}_st${i}` })) : [];
  return { datasetId, next: { ...d, datasets: [...d.datasets, { id: datasetId, name, sourceId, steps }] } };
}

export function updateDataset(d: Dashboard, id: string, patch: Partial<Dataset>): Dashboard {
  return { ...d, datasets: d.datasets.map((x) => (x.id === id ? { ...x, ...patch } : x)) };
}

export function removeDataset(d: Dashboard, id: string): Dashboard {
  return { ...d, datasets: d.datasets.filter((x) => x.id !== id) };
}

export function updateSteps(d: Dashboard, datasetId: string, fn: (steps: TransformStep[]) => TransformStep[]): Dashboard {
  return { ...d, datasets: d.datasets.map((x) => (x.id === datasetId ? { ...x, steps: fn(x.steps) } : x)) };
}

export function widgetsUsingDataset(d: Dashboard, datasetId: string) {
  return d.widgets.filter(
    (w) => ("binding" in w && w.binding.datasetId === datasetId) || (w.type === "filter" && w.options.datasetId === datasetId),
  );
}
